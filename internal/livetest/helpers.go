// OpenDB opens a pool for dsn through a Connector built with opts and closes
// it when the test ends.
func OpenDB(tb testing.TB, dsn string, opts ...quackdriver.Option) *sql.DB {
	tb.Helper()
	cn, err := quackdriver.NewConnector(dsn, opts...)
	if err != nil {
		tb.Fatalf("NewConnector(%q): %v", dsn, err)
	}
	db := sql.OpenDB(cn)
	tb.Cleanup(func() { _ = db.Close() })
	return db
}

// Conn takes a dedicated connection from db, returned when the test ends.
func Conn(tb testing.TB, db *sql.DB) *sql.Conn {
	tb.Helper()
	c, err := db.Conn(context.Background())
	if err != nil {
		tb.Fatalf("db.Conn: %v", err)
	}
	tb.Cleanup(func() { _ = c.Close() })
	return c
}

// Queryer is what *sql.DB, *sql.Conn and *sql.Tx have in common.
type Queryer interface {
	QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error)
	QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row
	ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error)
}

// Exec runs a statement, failing the test on error.
func Exec(tb testing.TB, q Queryer, query string, args ...any) sql.Result {
	tb.Helper()
	res, err := q.ExecContext(context.Background(), query, args...)
	if err != nil {
		tb.Fatalf("exec %q: %v", query, err)
	}
	return res
}

// Scalar runs a query returning one value, failing the test on error.
func Scalar[T any](tb testing.TB, q Queryer, query string, args ...any) T {
	tb.Helper()
	var v T
	if err := q.QueryRowContext(context.Background(), query, args...).Scan(&v); err != nil {
		tb.Fatalf("query %q: %v", query, err)
	}
	return v
}

// Eventually polls cond until it holds, failing the test after d.
func Eventually(tb testing.TB, d time.Duration, what string, cond func() bool) {
	tb.Helper()
	deadline := time.Now().Add(d)
	for !cond() {
		if time.Now().After(deadline) {
			tb.Fatalf("timed out after %v waiting for %s", d, what)
		}
		time.Sleep(20 * time.Millisecond)
	}
}

// SQLString quotes s as a SQL string literal.
func SQLString(s string) string { return sqlString(s) }

// Exchange is one recorded HTTP request and response body.
type Exchange struct{ Req, Resp []byte }

// Recorder is an http.RoundTripper that records every request and response
// body, so tests can inspect the exact Quack messages on the wire.
type Recorder struct {
	base http.RoundTripper
	mu   sync.Mutex
	xs   []Exchange
}

// NewRecorder returns a Recorder over a fresh http.Transport.
func NewRecorder() *Recorder {
	return &Recorder{base: &http.Transport{MaxIdleConnsPerHost: 32}}
}

// RoundTrip implements http.RoundTripper.
func (r *Recorder) RoundTrip(req *http.Request) (*http.Response, error) {
	var body []byte
	if req.Body != nil {
		b, err := io.ReadAll(req.Body)
		_ = req.Body.Close()
		if err != nil {
			return nil, err
		}
		body = b
		req.Body = io.NopCloser(bytes.NewReader(b))
	}
	resp, err := r.base.RoundTrip(req)
	var rb []byte
	if err == nil {
		rb, err = io.ReadAll(resp.Body)
		_ = resp.Body.Close()
		resp.Body = io.NopCloser(bytes.NewReader(rb))
	}
	r.mu.Lock()
	r.xs = append(r.xs, Exchange{Req: body, Resp: rb})
	r.mu.Unlock()
	if err != nil {
		return nil, err
	}
	return resp, nil
}

// Mark returns the number of exchanges recorded so far, for Since.
func (r *Recorder) Mark() int {
	r.mu.Lock()
	defer r.mu.Unlock()
	return len(r.xs)
}

// Since returns the exchanges recorded after mark.
func (r *Recorder) Since(mark int) []Exchange {
	r.mu.Lock()
	defer r.mu.Unlock()
	return append([]Exchange(nil), r.xs[mark:]...)
}

// TLSServer is a server serving HTTPS with a key pair generated by
// quack_generate_keys.
type TLSServer struct {
	*Server
	Dir         string         // holds server.pem and private_key.pem
	Fingerprint string         // SHA-256 of the DER certificate, uppercase hex
	Pool        *x509.CertPool // holds just the certificate
}

// StartTLSServer starts an HTTPS server on host; serveArgs are appended to
// quack_serve.
func StartTLSServer(tb testing.TB, host, serveArgs string) *TLSServer {
	tb.Helper()
	dir := tb.TempDir()
	cert := filepath.Join(dir, "server.pem")
	args := fmt.Sprintf("disable_ssl => false, ssl_cert_file => %s, ssl_key_file => %s",
		sqlString(cert), sqlString(filepath.Join(dir, "private_key.pem")))
	if serveArgs != "" {
		args += ", " + serveArgs
	}
	srv := StartServer(tb, ServerOptions{
		Host:      host,
		InitSQL:   "SELECT status FROM quack_generate_keys(directory := " + sqlString(dir) + ");",
		ServeArgs: args,
		TLS:       true,
	})
	pemBytes, err := os.ReadFile(cert)
	block, _ := pem.Decode(pemBytes)
	if block == nil {
		tb.Fatalf("livetest: no PEM certificate in %s: %v", cert, err)
		return nil
	}
	c, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		tb.Fatalf("livetest: parse certificate: %v", err)
	}
	sum := sha256.Sum256(block.Bytes)
	pool := x509.NewCertPool()
	pool.AddCert(c)
	return &TLSServer{Server: srv, Dir: dir, Fingerprint: strings.ToUpper(hex.EncodeToString(sum[:])), Pool: pool}
}

// Rows runs a query and returns every row as scanned values, failing the
// test on error.
func Rows(tb testing.TB, q Queryer, query string, args ...any) [][]any {
	tb.Helper()
	rows, err := q.QueryContext(context.Background(), query, args...)
	if err != nil {
		tb.Fatalf("query %q: %v", query, err)
	}
	defer rows.Close()
	cols, err := rows.Columns()
	if err != nil {
		tb.Fatal(err)
	}
	var out [][]any
	for rows.Next() {
		vals := make([]any, len(cols))
		ptrs := make([]any, len(cols))
		for i := range vals {
			ptrs[i] = &vals[i]
		}
		if err := rows.Scan(ptrs...); err != nil {
			tb.Fatalf("scan %q: %v", query, err)
		}
		out = append(out, vals)
	}
	if err := rows.Err(); err != nil {
		tb.Fatalf("rows %q: %v", query, err)
	}
	return out
}
